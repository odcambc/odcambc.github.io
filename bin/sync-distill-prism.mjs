import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);
const root = dirname(require.resolve("prismjs/package.json"));
const { version } = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
let source = readFileSync(join(root, "prism.js"), "utf8");

// Reject prototype-related and inherited keys when expanding a grammar's rest.
// This patch is needed even with Prism 1.30.0; keep it when refreshing Prism.
const original = "for (var token in rest) {\n\t\t\t\t\tgrammar[token] = rest[token];";
const replacement = `for (var token in rest) {
                    if (!Object.prototype.hasOwnProperty.call(rest, token) ||
                        token === "__proto__" || token === "constructor" || token === "prototype") {
                        continue;
                    }
                    grammar[token] = rest[token];`;
if (source.split(original).length !== 2) {
  throw new Error("Prism's grammar merge changed; review the security patch before syncing.");
}
source = source.replace(original, replacement);

for (const language of ["python", "lua", "bash", "go", "markdown", "julia"]) {
  source += "\n" + readFileSync(join(root, "components", `prism-${language}.js`), "utf8");
}

const destination = new URL("../assets/js/distillpub/", import.meta.url);
writeFileSync(new URL("prism.js", destination), `// Prism ${version}, MIT license. Generated by npm run sync:distill-prism.\n${source}`);
writeFileSync(new URL("PRISM-LICENSE.txt", destination), readFileSync(join(root, "LICENSE")));
